"""Reference candidates are source-derived, never auto-approved model outputs."""
import os
import unittest

from er2sql.module4_constraint_tests.gold_schema import parse_ground_truth_sql
from er2sql.module4_constraint_tests.generator import generate_constraint_tests
from er2sql.module7_evaluation.reference_normalization import normalize_source


class NormalizationTests(unittest.TestCase):
    def test_identity_keeps_options_and_warns_about_non_equivalence(self):
        for spelling, options in [('AUTO_INCREMENT', ''), ('AUTOINCREMENT', ''),
                                  ('IDENTITY(20, 3)', ' (START WITH 20 INCREMENT BY 3)')]:
            result = normalize_source(f'CREATE TABLE t(id INT PRIMARY KEY {spelling});')
            self.assertIn('GENERATED BY DEFAULT AS IDENTITY' + options, result['sql'])
            self.assertTrue(any('NULL/zero' in change for change in result['changes']))
        native = 'CREATE TABLE t(id INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY);'
        self.assertEqual(normalize_source(native)['sql'], native)
        self.assertTrue(normalize_source('CREATE TABLE t(id INT IDENTITY(1,0));')['blockers'])
        widened = normalize_source('CREATE TABLE t(id INT UNSIGNED AUTO_INCREMENT);')
        self.assertIn('id BIGINT GENERATED BY DEFAULT AS IDENTITY', widened['sql'])
        self.assertFalse(widened['blockers'])

    def test_quoted_forward_reference_uses_identifier_not_token_identity(self):
        result = normalize_source('CREATE TABLE `c` (`p` INT, FOREIGN KEY (`p`) REFERENCES `p` (`id`)); CREATE TABLE `p` (`id` INT PRIMARY KEY);')
        self.assertIn('ALTER TABLE c ADD FOREIGN KEY', result['sql'])
        self.assertIn('REFERENCES p (id)', result['sql'])
        inline = normalize_source('CREATE TABLE c(x INT CONSTRAINT fk REFERENCES p ON DELETE CASCADE); CREATE TABLE p(id INT PRIMARY KEY);')
        self.assertIn('ALTER TABLE c ADD CONSTRAINT fk FOREIGN KEY (x) REFERENCES p ON DELETE CASCADE;', inline['sql'])
        self.assertNotIn('CONSTRAINT fk', inline['sql'].split('CREATE TABLE p')[0])

    def test_array_brackets_are_not_empty_quoted_identifiers(self):
        native = 'CREATE TABLE t(id INT PRIMARY KEY, tags VARCHAR(20)[]);'
        self.assertEqual(normalize_source(native)['sql'], native)
        converted = normalize_source('CREATE TABLE `t` (id INT PRIMARY KEY, tags VARCHAR(20)[]);')
        self.assertIn('VARCHAR(20)[]', converted['sql'])

    def test_metadata_comments_preserved_without_affecting_constraints(self):
        result = normalize_source("CREATE TABLE t(id INT PRIMARY KEY COMMENT 'id text', v TEXT, UNIQUE INDEX (v)) ENGINE=InnoDB COMMENT='table text';")
        self.assertIn("COMMENT ON COLUMN t.id IS 'id text';", result['sql'])
        self.assertIn("COMMENT ON TABLE t IS 'table text';", result['sql'])
        self.assertIn('UNIQUE (v)', result['sql'])
        self.assertNotIn('ENGINE=', result['sql'])

    def test_indexes_preserve_unique_and_do_not_drop_prefix_semantics(self):
        result = normalize_source('CREATE TABLE `t` (`a` INT, b INT, UNIQUE KEY `uq` (`a`, b), KEY ix (b));')
        self.assertIn('UNIQUE (a, b)', result['sql'])
        self.assertNotIn('CONSTRAINT uq', result['sql'])
        self.assertIn('CREATE INDEX ON t (b);', result['sql'])
        prefix = normalize_source('CREATE TABLE t(a VARCHAR(99), UNIQUE KEY uq (a(10)));')
        self.assertIn('UNIQUE KEY uq (a(10))', prefix['sql'])

    def test_forward_foreign_key_preserves_target_and_actions(self):
        source = '''CREATE TABLE c(id INT PRIMARY KEY,p INT, CONSTRAINT fk FOREIGN KEY(p)
          REFERENCES p(id) ON DELETE CASCADE ON UPDATE RESTRICT);
          CREATE TABLE p(id INT PRIMARY KEY);'''
        result = normalize_source(source)
        self.assertGreater(result['sql'].index('ALTER TABLE c ADD'), result['sql'].index('CREATE TABLE p'))
        self.assertEqual(parse_ground_truth_sql(source, 's').ir, parse_ground_truth_sql(result['sql'], 's').ir)
        native = 'CREATE TABLE p(id INT PRIMARY KEY); CREATE TABLE c(x INT REFERENCES p(id));'
        self.assertEqual(normalize_source(native)['sql'], native)

    def test_no_reordering_across_mutations(self):
        source = '''CREATE TABLE c(p INT, FOREIGN KEY(p) REFERENCES p(id));
          CREATE TABLE p(id INT PRIMARY KEY); ALTER TABLE c DROP CONSTRAINT old;'''
        result = normalize_source(source)
        self.assertNotIn('ALTER TABLE c ADD', result['sql'])
        self.assertTrue(result['blockers'])

    def test_literals_comments_and_quoted_escape_stay_literal(self):
        source = """-- AUTO_INCREMENT `x`
          CREATE TABLE [a]]b](id INT PRIMARY KEY IDENTITY,
          note TEXT DEFAULT 'IDENTITY(1,2); ENGINE=x; CREATE TABLE user(x INT)');"""
        result = normalize_source(source)
        self.assertIn('CREATE TABLE "a]b"', result['sql'])
        self.assertIn("DEFAULT 'IDENTITY(1,2); ENGINE=x; CREATE TABLE user(x INT)'", result['sql'])
        self.assertIn('-- AUTO_INCREMENT `x`', result['sql'])

    def test_reserved_table_name_does_not_change_user_expression(self):
        result = normalize_source('CREATE TABLE user(id INT PRIMARY KEY, who TEXT DEFAULT USER);')
        self.assertIn('CREATE TABLE "user"', result['sql'])
        self.assertIn('DEFAULT USER', result['sql'])

    def test_quoted_identifier_lowercase_policy_and_collision_fallback(self):
        folded = normalize_source('CREATE TABLE `MixedName` (`ColumnName` INT PRIMARY KEY);')
        self.assertIn('CREATE TABLE mixedname', folded['sql'])
        self.assertIn('columnname INT', folded['sql'])
        collision = normalize_source('CREATE TABLE t(`Foo` INT, `foo` TEXT);')
        self.assertIn('"Foo" INT', collision['sql'])
        self.assertIn('"foo" TEXT', collision['sql'])
        separate_tables = normalize_source('CREATE TABLE a(`Foo` INT); CREATE TABLE b(`foo` INT);')
        self.assertIn('foo INT', separate_tables['sql'])
        self.assertNotIn('"Foo"', separate_tables['sql'])

    def test_policy_type_conversions_and_nonrepresentable_source_cases(self):
        for source in ['CREATE TABLE t(id NOT NULL);',
                       'CREATE TABLE t(id INT); CREATE TABLE t(id TEXT);',
                       'CREATE TABLE t(id INT(5,2));',
                       "CREATE TABLE t(id SET('A','B'));"]:
            with self.subTest(source=source):
                self.assertTrue(normalize_source(source)['blockers'])
        number = normalize_source('CREATE TABLE t(id NUMBER(*,0));')
        self.assertIn('id NUMERIC', number['sql'])
        self.assertFalse(number['blockers'])
        double = normalize_source('CREATE TABLE t(id DOUBLE(10,2));')
        self.assertIn('id DOUBLE PRECISION', double['sql'])
        self.assertFalse(double['blockers'])
        unsigned = normalize_source('CREATE TABLE t(id INT UNSIGNED);')
        self.assertIn('id BIGINT', unsigned['sql'])
        self.assertNotIn('CHECK', unsigned['sql'])
        self.assertFalse(unsigned['blockers'])
        enum = normalize_source("CREATE TABLE t(id ENUM('A','B'));" )
        self.assertIn("id TEXT CHECK (id IN ('A', 'B'))", enum['sql'])
        self.assertFalse(enum['blockers'])
        collated = normalize_source('CREATE TABLE t(id VARCHAR(10) COLLATE some_collation);')
        self.assertNotIn('COLLATE', collated['sql'])
        self.assertFalse(collated['blockers'])
        result = normalize_source('CREATE TABLE t(id NUMBER);')
        self.assertNotIn('PRIMARY KEY', result['sql'])
        self.assertIn('NUMERIC', result['sql'])

    def test_source_alter_add_drop_is_resolved_in_order(self):
        source = '''CREATE TABLE p(id INT PRIMARY KEY, obsolete INT);
          CREATE TABLE c(id INT PRIMARY KEY);
          ALTER TABLE c ADD COLUMN parent_id INT;
          ALTER TABLE c ADD CONSTRAINT c_parent_fk FOREIGN KEY(parent_id) REFERENCES p(id);
          ALTER TABLE c DROP FOREIGN KEY c_parent_fk;
          ALTER TABLE c ADD CONSTRAINT c_parent_fk FOREIGN KEY(parent_id) REFERENCES p(id);
          ALTER TABLE p DROP COLUMN obsolete;'''
        result = normalize_source(source)
        self.assertFalse(result['blockers'], result['blockers'])
        self.assertIn('parent_id INT', result['sql'])
        self.assertNotIn('obsolete', result['sql'])
        self.assertIn('FOREIGN KEY(parent_id) REFERENCES p(id)', result['sql'])
        self.assertNotIn('ALTER TABLE', result['sql'])

    def test_quoted_table_name_is_resolved_for_source_alter(self):
        source = 'CREATE TABLE `T` (`old` INT); ALTER TABLE `T` ADD COLUMN `new` INT; ALTER TABLE `T` DROP COLUMN `old`;'
        result = normalize_source(source)
        self.assertFalse(result['blockers'], result['blockers'])
        self.assertIn('new INT', result['sql'])
        self.assertNotIn('old INT', result['sql'])

    def test_hash_comments_do_not_mangle_column_parsing(self):
        source = 'CREATE TABLE t(id INT, # inline comment with comma,\n name VARCHAR(10));'
        result = normalize_source(source)
        self.assertFalse(result['blockers'], result['blockers'])
        self.assertIn('name VARCHAR(10)', result['sql'])
        self.assertNotIn('# inline comment', result['sql'])
        self.assertIn('-- inline comment', result['sql'])

    def test_v51_dialect_repair_cases(self):
        source = '''# schema-level note
          CREATE TABLE app.items (
            id INT PRIMARY KEY,
            flag BOOLEAN DEFAULT 1,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP()(),
            zeroed TIMESTAMP DEFAULT '0000-00-00 00:00:00',
            title VARCHAR(20) CHARACTER SET utf8mb4,
            x DOUBLE PRECISION precision,
            f FLOAT(10,2),
            INDEX (id) USING HASH,
            UNIQUE uq_title (title),
            UNIQUE KEY (id)
          );
          CREATE TABLE app.child (id INT, item_id INT,
            FOREIGN KEY (item_id) REFERENCES app.items(id));'''
        result = normalize_source(source)
        self.assertFalse(result['blockers'], result['blockers'])
        sql = result['sql']
        self.assertNotIn('# schema-level note', sql)
        self.assertIn('-- schema-level note', sql)
        self.assertIn('CREATE TABLE items', sql)
        self.assertIn('REFERENCES items(id)', sql)
        self.assertIn('flag BOOLEAN DEFAULT TRUE', sql)
        self.assertIn('created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP', sql)
        self.assertNotIn("'0000-00-00 00:00:00'", sql)
        self.assertIn('title VARCHAR(20)', sql)
        self.assertNotIn('CHARACTER SET', sql)
        self.assertNotIn('DOUBLE PRECISION precision', sql)
        self.assertIn('x DOUBLE PRECISION', sql)
        self.assertIn('f REAL', sql)
        self.assertIn('UNIQUE (title)', sql)
        self.assertIn('UNIQUE (id)', sql)
        self.assertIn('CREATE INDEX ON items (id)', sql)

    def test_v52_physical_options_and_timestamp_defaults(self):
        result = normalize_source('''CREATE TABLE t (
          id INT PRIMARY KEY AUTO_INCREMENT,
          a TIMESTAMP DEFAULT current_timestamp(),
          b TIMESTAMP DEFAULT(current_timestamp()),
          c TIMESTAMP DEFAULT current_timestamp()()
        ) ENGINE=InnoDB AUTO_INCREMENT=12 DEFAULT CHARACTER SET utf8mb4 COLLATE=utf8mb4_bin;''')
        self.assertFalse(result['blockers'], result['blockers'])
        sql = result['sql']
        self.assertNotIn('ENGINE=', sql)
        self.assertNotIn('AUTO_INCREMENT=12', sql)
        self.assertNotIn('DEFAULT CHARACTER SET', sql)
        self.assertNotIn('COLLATE=', sql)
        self.assertEqual(sql.upper().count('CURRENT_TIMESTAMP'), 3, sql)
        self.assertNotIn('CURRENT_TIMESTAMP()', sql)

    def test_omitted_reference_columns_use_only_declared_parent_pk(self):
        parsed = parse_ground_truth_sql('CREATE TABLE c(x INT REFERENCES p CHECK(x>0)); CREATE TABLE p(id INT PRIMARY KEY);', 's')
        self.assertFalse(parsed.warnings)
        self.assertEqual(parsed.ir['tables'][0]['foreign_keys'][0]['ref_columns'], ['id'])
        missing = parse_ground_truth_sql('CREATE TABLE c(x INT REFERENCES p); CREATE TABLE p(id INT UNIQUE);', 's')
        self.assertTrue(missing.warnings)
        self.assertEqual(missing.ir['tables'][0]['foreign_keys'][0]['ref_columns'], [])
        composite = parse_ground_truth_sql('CREATE TABLE c(x INT,y INT,FOREIGN KEY(x,y) REFERENCES p); CREATE TABLE p(a INT,b INT,PRIMARY KEY(a,b));', 's')
        self.assertFalse(composite.warnings)
        self.assertEqual(composite.ir['tables'][0]['foreign_keys'][0]['ref_columns'], ['a','b'])

    def test_bit_fixtures_and_table_scoped_spelling(self):
        from er2sql.module4_constraint_tests.value_factory import ValueFactory
        from er2sql.module5_verification.executor import _bind_identifier_spelling
        vf = ValueFactory()
        self.assertEqual(vf.dummy_value('BIT'), '1')
        self.assertEqual(vf.sentinel_invalid_value('BIT(3)'), '000')
        self.assertRegex(vf.dummy_value('BIT(3)'), r'^[01]{3}$')
        catalog = {'a':{'yns'}, 'b':{'yNs'}}
        sql = 'SELECT "yNs" FROM "a";'
        self.assertEqual(_bind_identifier_spelling(sql, {'yns','yNs','a','b'}, catalog), 'SELECT "yns" FROM "a";')
        self.assertEqual(_bind_identifier_spelling('SELECT "yNs" FROM "b";', set(), catalog), 'SELECT "yNs" FROM "b";')
        literal = 'INSERT INTO "a" ("yNs") VALUES (\'FROM "b"\');'
        self.assertEqual(_bind_identifier_spelling(literal, set(), catalog), 'INSERT INTO "a" ("yns") VALUES (\'FROM "b"\');')

    @unittest.skipUnless(os.environ.get('ER2SQL_RUN_POSTGRES_INTEGRATION') == '1', 'requires local PostgreSQL')
    def test_source_generated_suites_against_candidates(self):
        from er2sql.config import load_config
        from er2sql.module5_verification.db import build_connection
        from er2sql.module5_verification.executor import verify_schema
        config = load_config('config/config.yaml')
        cases = {
            'identity': 'CREATE TABLE t(id INT PRIMARY KEY AUTO_INCREMENT,v VARCHAR(10) UNIQUE);',
            'numeric': 'CREATE TABLE t(id NUMBER(4) PRIMARY KEY,n NUMBER(4,2) CHECK(n>0));',
            'forward': 'CREATE TABLE c(id INT PRIMARY KEY,p INT,FOREIGN KEY(p) REFERENCES p(id) ON DELETE CASCADE); CREATE TABLE p(id INT PRIMARY KEY);',
            'mysql_indexes': 'CREATE TABLE `t` (`id` INT PRIMARY KEY, `v` VARCHAR(10), UNIQUE KEY uq (`v`), KEY ix (`id`));',
            'reserved': 'CREATE TABLE user(id INT PRIMARY KEY); CREATE TABLE t(id INT PRIMARY KEY,u INT REFERENCES user(id));',
            'self_reference': 'CREATE TABLE t(id INT PRIMARY KEY AUTO_INCREMENT,manager_id INT REFERENCES t);',
            'bits': 'CREATE TABLE t(id INT PRIMARY KEY,flag BIT NOT NULL,code BIT(3) UNIQUE);',
            'column_case_scope': 'CREATE TABLE a(id INT PRIMARY KEY,yNs TEXT NOT NULL); CREATE TABLE b(id INT PRIMARY KEY,"yNs" TEXT NOT NULL);',
        }
        conn = build_connection(config.database)
        try:
            for name, source in cases.items():
                with self.subTest(name=name):
                    candidate = normalize_source(source)
                    parsed = parse_ground_truth_sql(source, name)
                    suite = generate_constraint_tests(parsed.ir, name, 'ground_truth_sql')
                    self.assertFalse(parsed.warnings + suite.generation_warnings + candidate['blockers'])
                    result = verify_schema(conn, candidate['sql'], suite, 'normalization_test', name, config.database.schema_prefix)
                    self.assertTrue(result.ddl_execution.success, result.as_dict())
                    self.assertGreater(result.tests_total, 0)
                    self.assertEqual(result.tests_passed, result.tests_total, result.as_dict())
        finally:
            conn.close()


if __name__ == '__main__':
    unittest.main()
