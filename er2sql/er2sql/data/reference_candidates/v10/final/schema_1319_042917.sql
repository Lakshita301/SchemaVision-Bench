CREATE TABLE sec_user (
    userId BIGINT NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    email VARCHAR(75) NOT NULL UNIQUE,
    encryptedPassword VARCHAR(128) NOT NULL,
    enabled BIT NOT NULL
);
CREATE TABLE sec_role(
    roleId BIGINT NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    roleName VARCHAR(30) NOT NULL UNIQUE
);
CREATE TABLE user_role
(
    id BIGINT NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    userId BIGINT NOT NULL,
    roleId BIGINT NOT NULL,
    CONSTRAINT user_role_fk1 FOREIGN KEY (userId)
  REFERENCES sec_user (userId),
    CONSTRAINT user_role_fk2 FOREIGN KEY (roleId)
  REFERENCES sec_role (roleId)
);
