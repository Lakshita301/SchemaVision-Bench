CREATE TABLE contains (
    orderid int NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    upc int NOT NULL,
    quantity SMALLINT NOT NULL,
    PRIMARY KEY (orderid,upc)
);

CREATE TABLE customer (
    customerid int NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    fname varchar(20) DEFAULT NULL,
    lname varchar(30) DEFAULT NULL,
    caddress varchar(100) DEFAULT NULL,
    ccity varchar(20) DEFAULT NULL,
    cstate char(2) DEFAULT NULL,
    czip char(5) DEFAULT NULL,
    PRIMARY KEY (customerid)
);

CREATE TABLE orders (
    orderid int NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    orderdate date DEFAULT NULL,
    shipdate date DEFAULT NULL,
    payment_type varchar(20) DEFAULT NULL,
    ccn char(16) DEFAULT NULL,
    customerid int DEFAULT NULL,
    PRIMARY KEY (orderid)
);

CREATE TABLE prod_category (
    upc int NOT NULL,
    category varchar(15) NOT NULL,
    PRIMARY KEY (upc,category)
);

CREATE TABLE product (
    upc int NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    pname varchar(40) DEFAULT NULL,
    price decimal(10,2) DEFAULT NULL,
    sname varchar(30) DEFAULT NULL,
    amount int DEFAULT NULL,
    reorderlevel int DEFAULT NULL,
    PRIMARY KEY (upc)
);

CREATE TABLE products_rated (
    upc int NOT NULL,
