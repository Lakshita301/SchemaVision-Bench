-- Tables detected: 5 | FK/REFERENCES mentions: 4
CREATE TABLE foods (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    description varchar(255) NOT NULL DEFAULT '',
    publication_date date NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE nutrients (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    name varchar(255) NOT NULL DEFAULT '',
    unit_name varchar(255) NOT NULL DEFAULT '',
    nutrient_code decimal(6,1) NOT NULL,
    rank BIGINT NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE users (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    name varchar(255) NOT NULL,
    email varchar(255) NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE user_foods (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    food_id BIGINT NOT NULL,
    servings_per_week BIGINT NOT NULL,
    PRIMARY KEY (id),
    FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    FOREIGN KEY (food_id) REFERENCES foods (id) ON DELETE CASCADE
);

CREATE TABLE food_nutrients (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    food_id BIGINT NOT NULL,
    nutrient_id BIGINT NOT NULL,
    amount_per_serving BIGINT NOT NULL,
    data_points BIGINT DEFAULT NULL,
    footnote varchar(255) DEFAULT NULL,
    PRIMARY KEY (id),
    FOREIGN KEY (nutrient_id) REFERENCES nutrients (id) ON DELETE CASCADE,
    FOREIGN KEY (food_id) REFERENCES foods (id) ON DELETE CASCADE
);
