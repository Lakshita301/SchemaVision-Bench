-- Tables detected: 3 | FK constraints: 2
CREATE TABLE ROOM(
    ROOM_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR(16) NOT NULL,
    ROOM_NUMBER CHAR(2) NOT NULL UNIQUE,
    BED_INFO CHAR(2) NOT NULL
);
CREATE TABLE GUEST(
    GUEST_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FIRST_NAME VARCHAR(64),
    LAST_NAME VARCHAR(64),
    EMAIL_ADDRESS VARCHAR(64),
    ADDRESS VARCHAR(64),
    COUNTRY VARCHAR(32),
    STATE VARCHAR(12),
    PHONE_NUMBER VARCHAR(24)
);
CREATE TABLE RESERVATION(
    RESERVATION_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ROOM_ID BIGINT NOT NULL,
    GUEST_ID BIGINT NOT NULL,
    RES_DATE DATE,
    FOREIGN KEY (ROOM_ID) REFERENCES ROOM(ROOM_ID)
);
ALTER TABLE RESERVATION ADD FOREIGN KEY (GUEST_ID) REFERENCES GUEST(GUEST_ID);
