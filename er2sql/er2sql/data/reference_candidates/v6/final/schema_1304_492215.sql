-- Tables detected: 13 | FK constraints: 19
CREATE TABLE users
(
    id NUMERIC NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firstname VARCHAR(50),
    lastname VARCHAR(50),
    email VARCHAR(120) UNIQUE,
    password_hash VARCHAR(100),
    phone NUMERIC UNIQUE
);

CREATE TABLE media_types
(
    id SERIAL,
    name VARCHAR(255),
    created_at TIMESTAMP DEFAULT NOW(),
    updated_at TIMESTAMP
);

CREATE TABLE media
(
    id SERIAL,
    media_type_id NUMERIC NOT NULL,
    user_id NUMERIC NOT NULL,
    body text,
    filename VARCHAR(255),
    size INT,
    metadata JSON,
    created_at TIMESTAMP DEFAULT NOW(),
    updated_at TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users (id),
    FOREIGN KEY (media_type_id) REFERENCES media_types (id)
);

CREATE TABLE profiles
(
    user_id NUMERIC NOT NULL UNIQUE,
    gender TEXT CHECK (gender IN ('f', 'm')),
    birthday DATE,
    photo_id NUMERIC NULL,
    created_at TIMESTAMP DEFAULT NOW(),
    hometown VARCHAR(100),
    FOREIGN KEY (user_id) REFERENCES users (id),
    FOREIGN KEY (photo_id) REFERENCES media (id)
);

CREATE TABLE messages
(
    id SERIAL,
    from_user_id NUMERIC NOT NULL,
    to_user_id NUMERIC NOT NULL,
    body TEXT,
    created_at TIMESTAMP DEFAULT NOW(),
    FOREIGN KEY (from_user_id) REFERENCES users (id),
    FOREIGN KEY (to_user_id) REFERENCES users (id)
);

CREATE TABLE friend_requests
(
    initiator_user_id NUMERIC NOT NULL,
    target_user_id NUMERIC NOT NULL,
    status TEXT CHECK (status IN ('requested', 'approved', 'declined', 'unfriended')),
    requested_at TIMESTAMP DEFAULT NOW(),
    updated_at TIMESTAMP,
    PRIMARY KEY (initiator_user_id, target_user_id),
    FOREIGN KEY (initiator_user_id) REFERENCES users (id),
    FOREIGN KEY (target_user_id) REFERENCES users (id)
);

CREATE TABLE communities
(
    id SERIAL,
    name VARCHAR(150),
    admin_user_id NUMERIC NOT NULL,
    foreign key (admin_user_id) references users (id)
);

CREATE TABLE users_communities
(
    user_id NUMERIC NOT NULL,
    community_id NUMERIC NOT NULL,
    PRIMARY KEY (user_id, community_id),
    FOREIGN KEY (user_id) REFERENCES users (id),
    FOREIGN KEY (community_id) REFERENCES communities (id)
);

CREATE TABLE likes
(
    id SERIAL,
    user_id NUMERIC NOT NULL,
    media_id NUMERIC NOT NULL,
    created_at TIMESTAMP DEFAULT NOW(),
    FOREIGN KEY (user_id) REFERENCES users (id),
    FOREIGN KEY (media_id) REFERENCES media (id)
);

CREATE TABLE photo_albums
(
    id SERIAL,
    name varchar(255)    DEFAULT NULL,
    user_id NUMERIC DEFAULT NULL,
    FOREIGN KEY (user_id) REFERENCES users (id),
    PRIMARY KEY (id)
);

CREATE TABLE photos
(
    id SERIAL,
    album_id NUMERIC NULL,
    media_id NUMERIC NOT NULL,
    FOREIGN KEY (album_id) REFERENCES photo_albums (id),
    FOREIGN KEY (media_id) REFERENCES media (id)
);

CREATE TABLE likes_messages
(
    id SERIAL,
    user_id NUMERIC NOT NULL,
    message_id NUMERIC NOT NULL,
    created_at TIMESTAMP DEFAULT NOW(),
    FOREIGN KEY (user_id) REFERENCES users (id) on delete cascade,
    FOREIGN KEY (message_id) REFERENCES messages (id) on delete cascade
);

CREATE TABLE likes_users
(
    id SERIAL,
    user_id NUMERIC NOT NULL,
    created_at TIMESTAMP DEFAULT NOW(),
    FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE INDEX ON users (firstname, lastname);
CREATE INDEX ON communities (name);
