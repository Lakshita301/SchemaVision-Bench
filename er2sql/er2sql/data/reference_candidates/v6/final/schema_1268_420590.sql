-- Tables detected: 4 | FK constraints: 3
CREATE TABLE tieba_sign_user (
    uid BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    username char(10) CHARACTER SET latin1 NOT NULL,
    salt char(10) CHARACTER SET latin1 NOT NULL,
    password char(40) CHARACTER SET latin1 NOT NULL,
    email varchar(255) CHARACTER SET latin1 NOT NULL,
    status SMALLINT DEFAULT '0' ,
    PRIMARY KEY (uid),
    CONSTRAINT username UNIQUE (username)
);

CREATE TABLE tieba_sign_cookies (
    cid BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    uid BIGINT NOT NULL DEFAULT '0',
    uname varchar(50) NOT NULL,
    cookie text NOT NULL,
    last_sign timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    end_sign date NOT NULL,
    forum_num BIGINT NOT NULL,
    status SMALLINT NOT NULL DEFAULT '1' ,
    PRIMARY KEY (cid),
    CONSTRAINT tieba_sign_cookies_ibfk_1 FOREIGN KEY (uid) REFERENCES tieba_sign_user (uid)
);

CREATE TABLE tieba_sign_history (
    hid BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    uid BIGINT NOT NULL,
    cid BIGINT NOT NULL,
    kw varchar(64) NOT NULL,
    type SMALLINT NOT NULL DEFAULT '1' ,
    time timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (hid),
    CONSTRAINT tieba_sign_history_ibfk_1 FOREIGN KEY (uid) REFERENCES tieba_sign_user (uid),
    CONSTRAINT tieba_sign_history_ibfk_2 FOREIGN KEY (cid) REFERENCES tieba_sign_cookies (cid)
);

CREATE TABLE tieba_sign_error_code (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    code int NOT NULL,
    usermsg TEXT NOT NULL,
    errmsg TEXT NOT NULL,
    PRIMARY KEY (id)
);
CREATE INDEX ON tieba_sign_user (username,status);
CREATE INDEX ON tieba_sign_user (email,status);
CREATE INDEX ON tieba_sign_cookies (status,uid,end_sign);
CREATE INDEX ON tieba_sign_cookies (uid);
CREATE INDEX ON tieba_sign_history (uid);
CREATE INDEX ON tieba_sign_history (time,type,cid);
COMMENT ON COLUMN tieba_sign_user.status IS '1已验证 0未验证 -1删除';
COMMENT ON COLUMN tieba_sign_cookies.status IS '1有效 0无效 -1删除';
COMMENT ON COLUMN tieba_sign_history.type IS '0、等等1、已签2、之前已签3、不支持';
