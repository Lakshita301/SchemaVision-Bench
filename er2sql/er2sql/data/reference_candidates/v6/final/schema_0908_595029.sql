    JOB_INSTANCE_ID NUMERIC(19,0)  NOT NULL PRIMARY KEY,
    VERSION NUMERIC(19,0),
    JOB_NAME VARCHAR(100 char) NOT NULL,
    JOB_KEY VARCHAR(32 char) NOT NULL,
    constraint JOB_INST_UN unique (JOB_NAME, JOB_KEY)
) ;

CREATE TABLE BATCH_JOB_EXECUTION  (
    JOB_EXECUTION_ID NUMERIC(19,0)  NOT NULL PRIMARY KEY,
    VERSION NUMERIC(19,0),
    JOB_INSTANCE_ID NUMERIC(19,0) NOT NULL,
    CREATE_TIME TIMESTAMP NOT NULL,
    START_TIME TIMESTAMP DEFAULT NULL,
    END_TIME TIMESTAMP DEFAULT NULL,
    STATUS VARCHAR(10 char),
    EXIT_CODE VARCHAR(2500 char),
    EXIT_MESSAGE VARCHAR(2500 char),
    LAST_UPDATED TIMESTAMP,
    JOB_CONFIGURATION_LOCATION VARCHAR(2500 char) NULL,
    constraint JOB_INST_EXEC_FK foreign key (JOB_INSTANCE_ID)
	references BATCH_JOB_INSTANCE(JOB_INSTANCE_ID)
) ;

