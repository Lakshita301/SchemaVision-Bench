-- Tables detected: 6 | FK constraints: 4
CREATE TABLE JOBINSTANCEDATA(
    jobinstanceid BIGINT NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(512),
    apptag VARCHAR(512)
);

CREATE TABLE EXECUTIONINSTANCEDATA(
    jobexecid BIGINT NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    jobinstanceid BIGINT,
    createtime TIMESTAMP,
    starttime TIMESTAMP,
    endtime TIMESTAMP,
    updatetime TIMESTAMP,
    parameters VARBINARY,
    batchstatus VARCHAR(512),
    exitstatus VARCHAR(512),
    CONSTRAINT JOBINST_JOBEXEC_FK FOREIGN KEY (jobinstanceid) REFERENCES JOBINSTANCEDATA (jobinstanceid)
);

CREATE TABLE STEPEXECUTIONINSTANCEDATA(
    stepexecid BIGINT NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    jobexecid BIGINT,
    batchstatus VARCHAR(512),
    exitstatus VARCHAR(512),
    stepname VARCHAR(512),
    readcount INTEGER,
    writecount INTEGER,
    commitcount INTEGER,
    rollbackcount INTEGER,
    readskipcount INTEGER,
    processskipcount INTEGER,
    filtercount INTEGER,
    writeskipcount INTEGER,
    startTime TIMESTAMP,
    endTime TIMESTAMP,
    persistentData VARBINARY,
    CONSTRAINT JOBEXEC_STEPEXEC_FK FOREIGN KEY (jobexecid) REFERENCES EXECUTIONINSTANCEDATA (jobexecid)
);

CREATE TABLE JOBSTATUS (
    id BIGINT NOT NULL PRIMARY KEY,
    obj VARBINARY,
    CONSTRAINT JOBSTATUS_JOBINST_FK FOREIGN KEY (id) REFERENCES JOBINSTANCEDATA (jobinstanceid) ON DELETE CASCADE
);

CREATE TABLE STEPSTATUS(
    id BIGINT NOT NULL PRIMARY KEY,
    obj VARBINARY,
    CONSTRAINT STEPSTATUS_STEPEXEC_FK FOREIGN KEY (id) REFERENCES STEPEXECUTIONINSTANCEDATA (stepexecid) ON DELETE CASCADE
);

CREATE TABLE CHECKPOINTDATA(
    id VARCHAR(512),
    obj VARBINARY
);
