-- Tables detected: 4 | FK constraints: 3
CREATE TABLE Cars (
    CarID SMALLINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    VIN CHAR(17) NOT NULL,
    Manufacturer VARCHAR(20),
    Model VARCHAR(20),
    Year YEAR,
    Color VARCHAR(10),
    PRIMARY KEY (CarID)
);

CREATE TABLE Customers (
    CustomerID SMALLINT GENERATED BY DEFAULT AS IDENTITY,
    ClientID CHAR(4) NOT NULL,
    Name VARCHAR(40) NOT NULL,
    Phone VARCHAR(20) NOT NULL,
    Email VARCHAR(40),
    Address VARCHAR(40),
    City VARCHAR(20),
    StateProvince VARCHAR(20),
    Country VARCHAR(30),
    PostalCode VARCHAR(10),
    PRIMARY KEY (CustomerID)
);

CREATE TABLE Salespersons (
    SalespersonID SMALLINT GENERATED BY DEFAULT AS IDENTITY,
    StaffID CHAR(4) NOT NULL,
    Name VARCHAR(40) NOT NULL,
    Store VARCHAR(40),
    PRIMARY KEY (SalespersonID)
);

CREATE TABLE Invoices (
    InvoiceID SMALLINT GENERATED BY DEFAULT AS IDENTITY,
    InvoiceNumber INT NOT NULL,
    Date DATE,
    CarID SMALLINT NOT NULL,
    CustomerID SMALLINT NOT NULL,
    SalespersonID SMALLINT NOT NULL,
    PRIMARY KEY (InvoiceID),
    FOREIGN KEY (CarID) REFERENCES Cars(CarID),
    FOREIGN KEY (SalespersonID) REFERENCES Salespersons(SalespersonID),
    FOREIGN KEY (CustomerID) REFERENCES Customers(CustomerID)
);
