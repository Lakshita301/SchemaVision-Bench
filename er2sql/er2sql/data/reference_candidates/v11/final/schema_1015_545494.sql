-- Tables detected: 3 | FK constraints: 2
CREATE TABLE Player(
    PlayerID INT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Player_FirstN VARCHAR(80) NOT NULL,
    Player_LastN VARCHAR(80) NOT NULL,
    Enroll_Time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    Coin INT
);

CREATE TABLE Bag(
    BagID INT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CropID INT,
    Crop_Num INT,
    PlayerID INT
);

CREATE TABLE Crop(
    CropID INT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CropName VARCHAR (80) NOT NULL,
    Buy_Price INT,
    Sell_Price INT
);
ALTER TABLE Bag ADD FOREIGN KEY (PlayerID) REFERENCES Player(PlayerID) ON DELETE CASCADE ON UPDATE CASCADE;
ALTER TABLE Bag ADD FOREIGN KEY(CropID) REFERENCES Crop(CropID) ON DELETE CASCADE ON UPDATE CASCADE;
