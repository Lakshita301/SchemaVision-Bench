-- Tables detected: 6 | FK constraints: 4
CREATE TABLE categoria (
    idcategoria int not null primary key GENERATED BY DEFAULT AS IDENTITY,
    descricao VARCHAR(45)
);

CREATE TABLE produto(
    idproduto int not null primary key GENERATED BY DEFAULT AS IDENTITY,
    descricao VARCHAR(45),
    preco float,
    idcategoria int,
    CONSTRAINT fkcategoria FOREIGN KEY (idcategoria)
references categoria (idcategoria)
);

CREATE TABLE vendas (
    idvenda int not null primary key GENERATED BY DEFAULT AS IDENTITY,
    data_venda date
);

CREATE TABLE vendas_has_produto(
    idvenda int,
    idproduto int,
    quantidade int,
    CONSTRAINT fkvenda FOREIGN key (idvenda)
REFERENCES vendas (idvenda),
    CONSTRAINT fkproduto FOREIGN KEY (idproduto)
REFERENCES produto(idproduto),
    PRIMARY KEY (idvenda,idproduto)
);

CREATE TABLE endereco(
    idendereco int not null primary key GENERATED BY DEFAULT AS IDENTITY,
    rua VARCHAR(45),
    bairro VARCHAR(45),
    numero INT,
    cidade VARCHAR(45)
);

CREATE TABLE vendedor(
    idvendedor int not null primary key GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(45),
    salario FLOAT,
    data_nasc DATE,
    idendereco int,
    CONSTRAINT fkendereco FOREIGN key (idendereco)
REFERENCES endereco (idendereco)
);
