CREATE TABLE relationship (
    uid1 int NOT NULL DEFAULT '0',
    uid2 int NOT NULL DEFAULT '0',
    type TEXT NOT NULL DEFAULT 'friend' CHECK (type IN ('friend', 'neighbour')),
    since timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (uid1,uid2,type)
);

CREATE TABLE threads (
    tid bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    subject varchar(40) NOT NULL,
    scope TEXT NOT NULL DEFAULT 'block' CHECK (scope IN ('personnel', 'block', 'neighbourhood', 'friends', 'neighbours')),
    scope_id int DEFAULT NULL,
    start_time timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (tid)
) ENGINE=InnoDB AUTO_INCREMENT=2 DEFAULT CHARSET=latin1;

