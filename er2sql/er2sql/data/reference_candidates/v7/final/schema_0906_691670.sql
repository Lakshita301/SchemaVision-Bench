-- Tables detected: 3 | FK constraints: 2
CREATE TABLE new (
    id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    title VARCHAR(400),
    author VARCHAR(100),
    body TEXT,
    source VARCHAR(20),
    url VARCHAR(200),
    created_at VARCHAR(40),
    overall_sentiment FLOAT,
    overall_magnitude FLOAT
);

CREATE TABLE sentence (
    id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    new_id INT NOT NULL,
    sentence VARCHAR(500),
    FOREIGN KEY (new_id) REFERENCES new(id)
);

CREATE TABLE sentiment (
    id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    sentence_id INT NOT NULL,
    sentiment SMALLINT,
    created_at TIMESTAMP,
    FOREIGN KEY (sentence_id) REFERENCES sentence(id)
);
