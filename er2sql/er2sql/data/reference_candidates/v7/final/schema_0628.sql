CREATE TABLE client (
    id_client int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nit varchar(13) DEFAULT NULL,
    name varchar(244) DEFAULT NULL,
    address varchar(244) DEFAULT NULL,
    state varchar(1) DEFAULT NULL
);

CREATE TABLE product (
    id_product int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name varchar(244) DEFAULT NULL,
    price DOUBLE PRECISION DEFAULT NULL,
    stock BIGINT DEFAULT NULL,
    state varchar(1) DEFAULT NULL
);

CREATE TABLE employee (
    id_employee int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    dpi BIGINT DEFAULT NULL,
    password varchar(40) DEFAULT NULL,
    name varchar(255) DEFAULT NULL,
    phone varchar(9) DEFAULT NULL,
    state varchar(1) DEFAULT NULL,
    "user" varchar(8) DEFAULT NULL
);

CREATE TABLE sales (
    id_sales int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_client int NOT NULL,
    id_employee int NOT NULL,
    serial_number varchar(244) DEFAULT NULL,
    sale_date date DEFAULT NULL,
    total_price DOUBLE PRECISION DEFAULT NULL,
    state varchar(1) DEFAULT NULL,
    FOREIGN KEY(id_client) REFERENCES client(id_client),
    FOREIGN KEY(id_employee) REFERENCES employee(id_employee)
);

CREATE TABLE sale_detail (
    id_sale_detail int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_sales int NOT NULL,
    id_product int NOT NULL,
    quantity BIGINT DEFAULT NULL,
    subtotal DOUBLE PRECISION DEFAULT NULL,
    FOREIGN KEY(id_Sales) REFERENCES  sales(id_sales),
    FOREIGN KEY(id_Product) REFERENCES product(id_product)
);
