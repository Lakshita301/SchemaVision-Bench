-- Tables detected: 11 | FK constraints: 10
CREATE TABLE StreetCus(
    id_stc INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    name VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE Customer(
    id_c INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    surname VARCHAR(255) NOT NULL,
    name VARCHAR(255) NOT NULL,
    patronymic VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    phone VARCHAR(255) NOT NULL UNIQUE,
    numberHouse INTEGER NOT NULL,
    numberFlat INTEGER NOT NULL,
    invitation BIT NOT NULL DEFAULT 0,
    id_stc INTEGER NOT NULL,
    FOREIGN KEY (id_stc) REFERENCES StreetCus(id_stc)
);

CREATE TABLE Subscription(
    id_s INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    price DECIMAL(5,2) NOT NULL,
    amountVisit INTEGER NOT NULL DEFAULT 0,
    validity DATE NOT NULL DEFAULT GETDATE()
);

CREATE TABLE Subscription_Cus(
    id_sc INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    id_s INTEGER NOT NULL,
    id_c INTEGER NOT NULL,
    FOREIGN KEY(id_s) REFERENCES Subscription(id_s),
    FOREIGN KEY(id_c) REFERENCES Customer(id_c)
);

CREATE TABLE StreetClub(
    id_stcl INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    name VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE Club(
    id_cl INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    phone VARCHAR(255) NOT NULL UNIQUE,
    numberHouse INTEGER NOT NULL,
    invitation BIT NOT NULL DEFAULT 1,
    id_stcl INTEGER NOT NULL,
    FOREIGN KEY(id_stcl) REFERENCES StreetClub(id_stcl)
);

CREATE TABLE TypePremise(
    id_tp INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    name VARCHAR(255) NOT NULL
);

CREATE TABLE Premise(
    id_p INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    invitation BIT NOT NULL DEFAULT 1,
    id_tp INTEGER NOT NULL,
    FOREIGN KEY(id_tp) REFERENCES TypePremise(id_tp)
);

CREATE TABLE Visit(
    id_v INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    date DATE NOT NULL UNIQUE,
    time TIME NOT NULL UNIQUE,
    id_c INTEGER NOT NULL,
    id_cl INTEGER NOT NULL,
    id_p INTEGER NOT NULL,
    FOREIGN KEY(id_c) REFERENCES Customer(id_c),
    FOREIGN KEY(id_cl) REFERENCES Club(id_cl),
    FOREIGN KEY(id_p) REFERENCES Premise(id_p)
);

CREATE TABLE TypeEquipment(
    id_te INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    name VARCHAR(255) NOT NULL
);

CREATE TABLE Equipment(
    id_e INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    name VARCHAR(255) NOT NULL,
    id_p INTEGER NOT NULL,
    id_te INTEGER NOT NULL,
    FOREIGN KEY(id_p) REFERENCES Premise(id_p),
    FOREIGN KEY(id_te) REFERENCES TypeEquipment(id_te)
);
