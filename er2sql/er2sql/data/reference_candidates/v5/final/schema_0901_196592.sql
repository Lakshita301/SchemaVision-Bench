    SCHEMA_VERSION varchar(25)
);

create table PLAYER (
    ID int GENERATED BY DEFAULT AS IDENTITY,
    AI_TYPE varchar(25),
    AI_LEVEL int,
    AI_XLIFE int,
    PLAYER_PROFILE varchar(36)
);

create table DECK_TYPE (
    ID int GENERATED BY DEFAULT AS IDENTITY,
    NAME varchar(15) not null
);

create table DECK (
    ID int GENERATED BY DEFAULT AS IDENTITY,
    NAME varchar(100),
    FILE_CHECKSUM bigint,
    DECK_TYPE_ID int,
    DECK_SIZE int,
    DECK_COLOR varchar(5)
);

create table GAME (
    TIME_START bigint primary KEY,
    MAG_VERSION varchar(7),
    CONCEDED boolean,
    TURNS int,
    START_HAND int,
    START_LIFE int,
    WINNING_PLAYER_NUMBER int
);

create table GAME_PLAYER (
    GAME_TIME_START bigint NOT NULL,
    PLAYER_NUMBER int NOT NULL,
    PLAYER_ID int,
    DECK_ID int
);


                         

