-- Tables detected: 4 | FK constraints: 1
CREATE TABLE findbugs_bugreport (
    id int NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    hash varchar(32) NOT NULL,
    bugreportid varchar(64) NOT NULL,
    whofiled varchar(64) NOT NULL,
    whenfiled TIMESTAMP NOT NULL,
    status varchar(64) default NULL,
    assignedto varchar(64) default NULL,
    componentid varchar(64) default NULL,
    componentname varchar(128) default NULL,
    PRIMARY KEY  (id)
)   ;
CREATE TABLE findbugs_evaluation (
    id int NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    issueid int NOT NULL,
    who varchar(128) NOT NULL,
    designation varchar(16) NOT NULL,
    comment text NOT NULL,
    time TIMESTAMP NOT NULL,
    PRIMARY KEY  (id)
) ;
CREATE TABLE findbugs_issue (
    id int NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    firstseen TIMESTAMP NOT NULL,
    lastseen TIMESTAMP NOT NULL,
    hash varchar(32) NOT NULL,
    bugpattern varchar(80) NOT NULL,
    priority int NOT NULL,
    primaryclass varchar(512) NOT NULL,
    PRIMARY KEY  (id),
    CONSTRAINT hash UNIQUE (hash)
) ;
CREATE TABLE findbugs_invocation (
    id int NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    who varchar(64) NOT NULL,
    entrypoint varchar(16) NOT NULL,
    datasource varchar(16) NOT NULL,
    fbversion varchar(16) NOT NULL,
    initialsynctime int NOT NULL,
    numissues int NOT NULL,
    starttime TIMESTAMP NOT NULL,
    endtime TIMESTAMP,
    PRIMARY KEY  (id)
);
ALTER TABLE findbugs_evaluation ADD CONSTRAINT findbugs_evaluation_ibfk_1 FOREIGN KEY (issueid) REFERENCES findbugs_issue (id) ON DELETE CASCADE;
CREATE INDEX ON findbugs_bugreport (hash);
CREATE INDEX ON findbugs_evaluation (issueid);
COMMENT ON TABLE findbugs_bugreport IS 'Keeps track of bugs filed against FindBugs issues';
