create table tb_college
(
    col_id BIGINT GENERATED BY DEFAULT AS IDENTITY ,
    col_name varchar(50) not null ,
    col_intro varchar(5000) default '' ,
    primary key (col_id)
) engine=innodb comment '学院表';

create table tb_student
(
    stu_id BIGINT not null ,
    stu_name varchar(20) not null ,
    stu_sex boolean default 1 ,
    stu_birth date not null ,
    stu_addr varchar(255) default '' ,
    col_id BIGINT not null ,
    primary key (stu_id),
    foreign key (col_id) references tb_college (col_id)
) engine=innodb comment '学生表';

create table tb_teacher
(
    tea_id BIGINT not null ,
    tea_name varchar(20) not null ,
    tea_title varchar(10) default '助教' ,
    col_id BIGINT not null ,
    primary key (tea_id),
    foreign key (col_id) references tb_college (col_id)
) engine=innodb comment '老师表';

create table tb_course
(
    cou_id BIGINT not null ,
    cou_name varchar(50) not null ,
    cou_credit BIGINT not null ,
    tea_id BIGINT not null ,
    primary key (cou_id),
    foreign key (tea_id) references tb_teacher (tea_id)
) engine=innodb comment '课程表';

create table tb_record
(
    rec_id NUMERIC GENERATED BY DEFAULT AS IDENTITY ,
    sid BIGINT not null ,
    cid BIGINT not null ,
    sel_date date not null ,
    score decimal(4,1) ,
    primary key (rec_id),
    foreign key (sid) references tb_student (stu_id),
    foreign key (cid) references tb_course (cou_id),
    unique (sid, cid)
) engine=innodb comment '选课记录表';
