CREATE TABLE venue (
    venue_id int not null GENERATED BY DEFAULT AS IDENTITY,
    name varchar(255),
    number_venue varchar(20),
    street varchar(255),
    suburb varchar(100),
    postcode int,
    city varchar(100),
