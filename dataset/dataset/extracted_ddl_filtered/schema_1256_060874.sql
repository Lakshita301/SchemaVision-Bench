-- Tables detected: 5 | FK constraints: 5

CREATE TABLE STUDENT ( 
USN VARCHAR (10), 
SNAME VARCHAR (25), 
ADDRESS VARCHAR (25), 
PHONE LONG, 
GENDER CHAR (1),
PRIMARY KEY (USN));

CREATE TABLE SEMSEC ( 
SSID VARCHAR (5), 
SEM INT, 
SEC CHAR (1),
PRIMARY KEY (SSID));

CREATE TABLE CLASS ( 
USN VARCHAR (10), 
SSID VARCHAR (5), 
PRIMARY KEY (USN, SSID), 
FOREIGN KEY (USN) REFERENCES STUDENT (USN), 
FOREIGN KEY (SSID) REFERENCES SEMSEC (SSID));

CREATE TABLE SUBJECT ( 
SUBCODE VARCHAR (8), 
TITLE VARCHAR (20), 
SEM INT, 
CREDITS INT, 
PRIMARY KEY (SUBCODE));

CREATE TABLE IAMARKS ( 
USN VARCHAR (10), 
SUBCODE VARCHAR (8), 
SSID VARCHAR (5), 
TEST1 INT, 
TEST2 INT, 
TEST3 INT, 
FINALIA INT, 
PRIMARY KEY (USN, SUBCODE, SSID), 
FOREIGN KEY (USN) REFERENCES STUDENT (USN), 
FOREIGN KEY (SUBCODE) REFERENCES SUBJECT (SUBCODE), 
FOREIGN KEY (SSID) REFERENCES SEMSEC (SSID));

